import argparse
from datetime import datetime, timezone
import select
import socket
import sys
import time
import uuid

from traffic import (
    PACKET_HEADER,
    TRAFFIC_CLASSES,
    ResponseTracker,
    append_csv,
    encode_packet,
    packet_counts,
    positive_float,
    rtt_summary,
    valid_port,
)


def build_parser():
    parser = argparse.ArgumentParser(
        description="Generate and measure one class of UDP traffic."
    )
    parser.add_argument("--host", default="10.0.0.4", help="Destination server IP")
    parser.add_argument(
        "--class",
        dest="traffic_class",
        choices=TRAFFIC_CLASSES,
        default="high",
        help="Traffic class; determines the default destination port",
    )
    parser.add_argument(
        "--port",
        type=valid_port,
        help="Override the destination UDP port selected by --class",
    )
    parser.add_argument(
        "--source-port",
        type=valid_port,
        help="Local UDP port; bind to the class port to preserve reply classification",
    )
    parser.add_argument(
        "--rate", type=positive_float, default=100, help="Target packets per second"
    )
    parser.add_argument(
        "--seconds", type=positive_float, default=5, help="Traffic generation duration"
    )
    parser.add_argument(
        "--packet-size",
        "--payload-size",
        dest="packet_size",
        type=int,
        default=256,
        help="UDP payload size in bytes, including the app header (alias: --payload-size)",
    )
    parser.add_argument(
        "--reply-timeout",
        type=positive_float,
        default=1,
        help="Seconds to wait for delayed UDP echo replies",
    )
    parser.add_argument(
        "--flow-id",
        type=uuid.UUID,
        help="Optional UUID for this flow; a unique UUID is generated by default",
    )
    parser.add_argument(
        "--experiment-id",
        help="Experiment ID shared with the server and other clients",
    )
    parser.add_argument("--csv", help="Append this run's measurements to a CSV file")
    return parser


def drain_responses(sock, tracker, response_bytes):
    while True:
        try:
            data = sock.recv(65535)
        except BlockingIOError:
            return response_bytes

        status, _ = tracker.process_response(data, time.monotonic_ns())
        if status in ("received", "out_of_order"):
            response_bytes += len(data)


def main():
    parser = build_parser()
    args = parser.parse_args()
    if not PACKET_HEADER.size <= args.packet_size <= 65507:
        parser.error(
            "--packet-size must be between {} and 65507 bytes".format(
                PACKET_HEADER.size
            )
        )

    port = (
        args.port
        if args.port is not None
        else TRAFFIC_CLASSES[args.traffic_class]["port"]
    )
    expected_port = TRAFFIC_CLASSES[args.traffic_class]["port"]
    if port != expected_port:
        controller_class = next(
            (
                name
                for name, config in TRAFFIC_CLASSES.items()
                if config["port"] == port
            ),
            "low (default)",
        )
        print(
            "Warning: this controller classifies destination port {} as {}; "
            "the app packet remains {}.".format(
                port, controller_class, args.traffic_class
            ),
            file=sys.stderr,
        )
    if args.source_port is not None and args.source_port != expected_port:
        print(
        "Warning: the controller classifies replies to source port {} as LOW "
        "unless it is one of the configured class ports.".format(
            args.source_port
        ),
        file=sys.stderr,
        )

    flow_uuid = args.flow_id or uuid.uuid4()
    flow_id = flow_uuid.bytes
    flow_id_hex = flow_uuid.hex
    experiment_id = args.experiment_id or uuid.uuid4().hex
    tracker = ResponseTracker(args.traffic_class, flow_id)
    response_bytes = 0
    sequence = 0
    interval = 1 / args.rate

    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setblocking(False)
    try:
        if args.source_port is not None:
            sock.bind(("0.0.0.0", args.source_port))
        sock.connect((args.host, port))
        local_port = sock.getsockname()[1]
        send_start = time.monotonic()
        send_deadline = send_start + args.seconds
        next_send = send_start
        while True:
            now = time.monotonic()
            if now >= send_deadline:
                break

            if now >= next_send:
                sent_at_ns = time.monotonic_ns()
                packet = encode_packet(
                    args.traffic_class,
                    sequence,
                    sent_at_ns,
                    flow_id,
                    args.packet_size,
                )
                sock.send(packet)
                tracker.register_send(sequence, sent_at_ns)
                sequence += 1
                next_send += interval
                if next_send < time.monotonic():
                    next_send = time.monotonic() + interval
                continue

            ready, _, _ = select.select(
                [sock], [], [], min(next_send - now, send_deadline - now)
            )
            if ready:
                response_bytes = drain_responses(sock, tracker, response_bytes)

        send_elapsed = max(time.monotonic() - send_start, 1e-9)
        receive_deadline = time.monotonic() + args.reply_timeout
        while time.monotonic() < receive_deadline:
            wait = receive_deadline - time.monotonic()
            ready, _, _ = select.select([sock], [], [], wait)
            if not ready:
                break
            response_bytes = drain_responses(sock, tracker, response_bytes)
        measurement_elapsed = max(time.monotonic() - send_start, send_elapsed)
    finally:
        sock.close()

    packets = packet_counts(
        len(tracker.sent_times), len(tracker.received_times)
    )
    offered_mbps = (
        packets["packets_sent"]
        * args.packet_size
        * 8
        / (send_elapsed * 1_000_000)
    )
    echo_mbps = response_bytes * 8 / (measurement_elapsed * 1_000_000)
    rtts = [
        (received_ns - tracker.sent_times[seq]) / 1_000_000
        for seq, received_ns in tracker.received_times.items()
    ]
    rtt = rtt_summary(rtts)
    timestamp = datetime.now(timezone.utc).isoformat()
    print(
        "timestamp_utc={} experiment_id={} class={} flow_id={} "
        "source_port={} destination={}:{} packets_sent={} packets_received={} packets_lost={} "
        "loss={:.2f}% offered_throughput={:.3f}Mbps "
        "echo_throughput={:.3f}Mbps avg_rtt={} "
        "min_rtt={} max_rtt={} duplicates={} "
        "out_of_order={} invalid={} unexpected={}".format(
            timestamp,
            experiment_id,
            args.traffic_class,
            flow_id_hex,
            local_port,
            args.host,
            port,
            packets["packets_sent"],
            packets["packets_received"],
            packets["packets_lost"],
            packets["loss_percent"],
            offered_mbps,
            echo_mbps,
            "{:.3f}ms".format(rtt["avg_rtt_ms"])
            if rtt["avg_rtt_ms"] is not None
            else "n/a",
            "{:.3f}ms".format(rtt["min_rtt_ms"])
            if rtt["min_rtt_ms"] is not None
            else "n/a",
            "{:.3f}ms".format(rtt["max_rtt_ms"])
            if rtt["max_rtt_ms"] is not None
            else "n/a",
            tracker.duplicate_packets,
            tracker.out_of_order_packets,
            tracker.invalid_packets,
            tracker.unexpected_packets,
        )
    )
    print(
        "received_throughput is measured by the server per class; "
        "echo_throughput is valid echoed bytes received by this client."
    )

    if args.csv:
        append_csv(
            args.csv,
            {
                "timestamp_utc": timestamp,
                "experiment_id": experiment_id,
                "record_type": "client_flow",
                "traffic_class": args.traffic_class,
                "flow_id": flow_id_hex,
                "destination_ip": args.host,
                "destination_port": port,
                "source_port": local_port,
                "packet_size_bytes": args.packet_size,
                "target_rate_pps": args.rate,
                "duration_s": args.seconds,
                "packets_sent": packets["packets_sent"],
                "packets_received": packets["packets_received"],
                "packets_lost": packets["packets_lost"],
                "duplicate_packets": tracker.duplicate_packets,
                "out_of_order_packets": tracker.out_of_order_packets,
                "invalid_packets": tracker.invalid_packets,
                "unexpected_packets": tracker.unexpected_packets,
                "loss_percent": packets["loss_percent"],
                "offered_throughput_mbps": offered_mbps,
                "echo_throughput_mbps": echo_mbps,
                "avg_rtt_ms": rtt["avg_rtt_ms"],
                "min_rtt_ms": rtt["min_rtt_ms"],
                "max_rtt_ms": rtt["max_rtt_ms"],
            },
        )


if __name__ == "__main__":
    main()
